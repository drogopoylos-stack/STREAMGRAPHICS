const dicts = { en };
let dict = en;

export function setLang(code) {
  if (dicts[code]) { dict = dicts[code]; LANG.code = code; }
}

/** t('teams.sub', { n: 3 }) → string. Arrays/objects are returned as-is. Missing → the key. */
export function t(key, vars) {
  let v = key.split('.').reduce((o, k) => (o == null ? o : o[k]), dict);
  if (v == null) v = key.split('.').reduce((o, k) => (o == null ? o : o[k]), en);
  if (v == null) return key;
  if (typeof v !== 'string' || !vars) return v;
  return v.replace(/\{(\w+)\}/g, (m, k) => (vars[k] ?? m));
}

const DATE_CACHE = new Map();
/** Format a YYYY-MM-DD date in the UI locale. style: 'long' | 'short' | 'weekday' */
export function fmtDate(iso, style = 'long') {
  if (!iso) return '';
  const [y, m, d] = iso.split('-').map(Number);
  if (!y || !m || !d) return iso;
  const opts = {
    long: { weekday: 'long', day: 'numeric', month: 'long', year: 'numeric' },
    short: { weekday: 'short', day: 'numeric', month: 'short' },
    weekday: { weekday: 'short', day: 'numeric', month: 'short' },
  }[style] ?? {};
  const k = style;
  if (!DATE_CACHE.has(k)) DATE_CACHE.set(k, new Intl.DateTimeFormat(LANG.locale, { ...opts, timeZone: 'UTC' }));
  return DATE_CACHE.get(k).format(new Date(Date.UTC(y, m - 1, d, 12)));
}

const STAMP_CACHE = new Map();
const stampFmt = (key, opts) => {
  if (!STAMP_CACHE.has(key)) STAMP_CACHE.set(key, new Intl.DateTimeFormat(LANG.locale, opts));
  return STAMP_CACHE.get(key);
};
/** Format a timestamp (ms, local clock) as "Today 14:32", "Yesterday 09:10" or "Wed 28 Oct 14:32". */
export function fmtStamp(ms) {
  const d = new Date(ms);
  if (Number.isNaN(d.getTime())) return '';
  const time = stampFmt('time', { hour: '2-digit', minute: '2-digit' }).format(d);
  const now = new Date();
  const yest = new Date(now); yest.setDate(now.getDate() - 1);
  if (d.toDateString() === now.toDateString()) return `${t('common.todayAt')} ${time}`;
  if (d.toDateString() === yest.toDateString()) return `${t('common.yesterdayAt')} ${time}`;
  const sameYear = d.getFullYear() === now.getFullYear();
  const date = stampFmt(sameYear ? 'd' : 'dy', sameYear ? { weekday: 'short', day: 'numeric', month: 'short' } : { day: 'numeric', month: 'short', year: 'numeric' }).format(d);
  return `${date} ${time}`;
}
